/**
 * MEDIA PIPELINE
 *
 *   node scripts/prep-media.mjs
 *
 * 1. Encodes the live-site captures in `design/captures/*.png` (taken from the
 *    real, deployed projects with headless Chrome) to WebP under
 *    `public/images/work/<project>/`.
 * 2. Writes `src/content/media.generated.ts` — width, height and a blur
 *    placeholder for every portfolio image, including ones produced earlier by
 *    `prep-screenshots.mjs`. Content files reference images by key, so a
 *    re-capture never means hand-copying dimensions again.
 *
 * Nothing is recoloured, retouched or composited. Crops are never applied to
 * the interface itself.
 */
import sharp from "sharp";
import { mkdir, readdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";

const CAPTURES = "design/captures";
const WORK = "public/images/work";

/** capture file → published key. Desktop shots are 1440×900 @1.5x, mobile 390×844 @2x. */
const jobs = {
  "dahab-desktop": "dahab-el-araby/desktop",
  "dahab-mobile": "dahab-el-araby/mobile-dark",
  "dahab-mobile-light": "dahab-el-araby/mobile-light",
  "shopik-desktop": "shopik-lopik/home",
  "shopik-desktop-cats": "shopik-lopik/categories",
  "shopik-desktop-category": "shopik-lopik/subcategories",
  "shopik-mobile": "shopik-lopik/mobile-home",
  "shopik-mobile-cats": "shopik-lopik/mobile-categories",
  "gym-desktop": "verra/home",
  "gym-desktop-intro": "verra/story",
  "gym-desktop-rooms": "verra/experience",
  "gym-desktop-timetable": "verra/classes",
  "gym-desktop-coaches": "verra/coaches",
  "gym-mobile": "verra/mobile-home",
  "gym-mobile-rooms": "verra/mobile-experience",
  "bay3-mobile": "bay3/mobile-home",
  "bay3-mobile-products": "bay3/mobile-catalog",
  "bay3-mobile-product": "bay3/mobile-product",
  "hajaty-mobile": "hajaty-day3a/mobile-home",
};

for (const [file, key] of Object.entries(jobs)) {
  const input = `${CAPTURES}/${file}.png`;
  const { width } = await sharp(input).metadata();
  const isMobile = width < 1000;
  await mkdir(path.dirname(`${WORK}/${key}`), { recursive: true });
  await sharp(input)
    .resize({ width: isMobile ? 780 : 1600 })
    .webp({ quality: isMobile ? 82 : 80, effort: 6 })
    .toFile(`${WORK}/${key}.webp`);
}

/* ── Manifest ──────────────────────────────────────────────────────────── */
async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = `${dir}/${entry.name}`;
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (entry.name.endsWith(".webp")) out.push(full);
  }
  return out;
}

const manifest = {};
let bytes = 0;
for (const file of (await walk(WORK)).sort()) {
  const key = file.slice(WORK.length + 1).replace(/\.webp$/, "");
  const { width, height } = await sharp(file).metadata();
  const blur = await sharp(file).resize({ width: 16 }).webp({ quality: 40 }).toBuffer();
  bytes += (await stat(file)).size;
  manifest[key] = {
    src: `/images/work/${key}.webp`,
    width,
    height,
    blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
  };
}

const ts = `/* eslint-disable */
// GENERATED by scripts/prep-media.mjs — do not edit by hand.
// Real screenshots of deployed WebCraft projects.

export const media = ${JSON.stringify(manifest, null, 2)} as const;

export type MediaKey = keyof typeof media;
`;
await writeFile("src/content/media.generated.ts", ts);
console.log(Object.keys(manifest).length, "images,", (bytes / 1024).toFixed(0), "kB total");
